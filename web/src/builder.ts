// Turns a form description of a simple game (G, F, GF or FG objective) into a GenSys-LTL script.

export type GameType = "Int" | "Real" | "Bool";
export type Objective = "safety" | "reachability" | "buchi" | "cobuchi";

export interface Move {
  name: string;
  constraints: string;
}

export interface GameSpec {
  title: string;
  variables: string;
  type: GameType;
  objective: Objective;
  goal: string;
  environment: string;
  moves: Move[];
  init: string;
}

export const OBJECTIVES: Record<Objective, { label: string; ltl: string; fn: string }> = {
  safety: { label: "Safety", ltl: "G", fn: "safety_fixedpoint_gensys" },
  reachability: { label: "Reachability", ltl: "F", fn: "reachability_fixedpoint_gensys" },
  buchi: { label: "Büchi", ltl: "GF", fn: "buchi_fixedpoint_gensys" },
  cobuchi: { label: "co-Büchi", ltl: "FG", fn: "cobuchi_fixedpoint_gensys" },
};

export const DEFAULT_GAME: GameSpec = {
  title: "Robot on a line",
  variables: "x",
  type: "Int",
  objective: "safety",
  goal: "x >= 0\nx <= 10",
  environment: "x_ >= x - 1\nx_ <= x + 1",
  moves: [
    { name: "left", constraints: "x_ == x - 1" },
    { name: "stay", constraints: "x_ == x" },
    { name: "right", constraints: "x_ == x + 1" },
  ],
  init: "x == 5",
};

const PY_KEYWORDS = new Set(
  ("False None True and as assert async await break class continue def del elif else except finally for from " +
    "global if import in is lambda nonlocal not or pass raise return try while with yield").split(" "),
);
// Names the generated script already uses, or that `from z3 import *` / `from gensys.fixpoints import *` bring in.
const RESERVED = new Set(
  ("And Or Not Implies If Xor Distinct Sum Int Real Bool Ints Reals Bools Exists ForAll Solver Goal Tactic sys " +
    "game_type controller_moves environment guarantee init move min project succ").split(" "),
);

function splitList(text: string): string[] {
  return text
    .split(/[\s,]+/)
    .map((v) => v.trim())
    .filter(Boolean);
}

function checkName(name: string, what: string, errors: string[]) {
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(name)) {
    errors.push(`${what} "${name}" must start with a letter and contain only letters and digits (no underscores).`);
  } else if (PY_KEYWORDS.has(name) || RESERVED.has(name)) {
    errors.push(`${what} "${name}" is a reserved name; please choose another.`);
  }
}

export function validate(spec: GameSpec): string[] {
  const errors: string[] = [];
  const vars = splitList(spec.variables);
  if (vars.length === 0) errors.push("Declare at least one state variable.");
  vars.forEach((v) => checkName(v, "Variable", errors));
  if (new Set(vars).size !== vars.length) errors.push("State variable names must be unique.");
  if (spec.moves.length === 0) errors.push("Add at least one controller move.");
  const moveNames = spec.moves.map((m) => m.name.trim());
  moveNames.forEach((m) => checkName(m, "Move", errors));
  moveNames.forEach((m) => vars.includes(m) && errors.push(`Move "${m}" has the same name as a variable.`));
  if (new Set(moveNames).size !== moveNames.length) errors.push("Controller move names must be unique.");
  if (!spec.goal.trim()) errors.push("The objective needs at least one constraint.");
  return errors;
}

// One constraint per line; several lines are combined with And(...).
function conjunction(text: string, empty: string): string {
  const parts = text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
  if (parts.length === 0) return empty;
  if (parts.length === 1) return parts[0];
  return `And(${parts.join(", ")})`;
}

export function generate(spec: GameSpec): string {
  const vars = splitList(spec.variables);
  const primed = vars.map((v) => `${v}_`);
  const cur = vars.join(", ");
  const trans = [...vars, ...primed].join(", ");
  const obj = OBJECTIVES[spec.objective];
  const goal = conjunction(spec.goal, "True");
  const moveNames = spec.moves.map((m) => m.name.trim());
  const title = spec.title.trim() || "Custom game";

  const moves = spec.moves
    .map((m, i) => `def ${moveNames[i]}(${trans}):\n    return ${conjunction(m.constraints, "True")}\n`)
    .join("\n");

  return `from gensys.helper import *
from gensys.fixpoints import *
from z3 import *

# ${title}
# Specification: ${obj.label}, ${obj.ltl}(${goal})
# Generated by the GenSys-LTL playground. A variable v is the current state and v_ the next state.

# 0. Define game type (Int/ Real/ Bool)
game_type = "${spec.type}"

# 1. Define Environment moves
def environment(${trans}):
    return ${conjunction(spec.environment, "True")}

# 2. Define Controller moves (the controller plays first and picks one move per turn)
${moves}
controller_moves = [${moveNames.join(", ")}]

# 3. Define Init Region (False => the maximal winning region is computed)
def init(${cur}):
    return ${conjunction(spec.init, "False")}

# 4. Define Guarantee: the objective is ${obj.ltl}(guarantee)
def guarantee(${cur}):
    return ${goal}

${obj.fn}(controller_moves, environment, guarantee, 0, game_type, init)
`;
}
